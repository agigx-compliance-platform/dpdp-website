/**
 * Generic static DPDP advisory prompt generator for Privacy Pitstop.
 *
 * Requirements:
 * - Exactly ONE reusable static prompt template.
 * - Only the URL entered by the user in Privacy Pitstop changes.
 * - No hardcoded website-specific findings, scores, industry descriptions, or recommendations.
 */

export const GENERIC_DPDP_LLM_PROMPT_TEMPLATE = `@Web search

You are an experienced DPDP (Digital Personal Data Protection Act, 2023) readiness advisor.

I want to understand the privacy practices and DPDP compliance considerations of the following website.

WEBSITE URL:
{{CURRENT_USER_ENTERED_URL}}

YOUR TASK:

1. Visit and analyse the supplied website. Identify its business domain, industry, services and publicly available privacy practices.

2. Explain what the Digital Personal Data Protection (DPDP) Act, 2023 is, why it matters and how it applies to businesses operating in India.

3. Explain what a DPDP readiness score represents and why organisations need to assess their privacy and data protection readiness.

4. Independently evaluate the website against relevant DPDP requirements, including:
   - Privacy notices and transparency.
   - Consent collection and withdrawal.
   - Purpose limitation and data minimisation.
   - Personal data processing and security.
   - Children's personal data, where applicable.
   - Data retention and erasure.
   - Data Principal rights.
   - Grievance redressal.
   - Third-party processors and data sharing.
   - Cookies, analytics and marketing practices.
   - Governance and accountability.

5. Explain how DPDP readiness scores are generally evaluated, including the importance of assessment categories, scoring criteria, evidence, identified gaps and risk levels.

6. Explain what factors could result in a higher or lower privacy readiness score for this particular website.

7. Identify potential compliance gaps, strengths and areas requiring further investigation. Clearly distinguish verified facts from assumptions.

8. Explain why businesses should improve their DPDP readiness and the potential operational and compliance implications of not addressing identified gaps.

9. Provide practical recommendations to improve privacy readiness, prioritised by business impact and implementation urgency.

10. Explain what additional information would be needed to calculate or independently verify an exact DPDP readiness score.

IMPORTANT:

- Base your assessment on the actual website and reliable regulatory sources.
- Do not fabricate findings, scores, scoring weights or compliance gaps.
- Do not assume that the website's actual internal Privacy Pitstop scoring formula is publicly available.
- Distinguish a general DPDP readiness assessment from the exact score generated by Privacy Pitstop.
- Do not treat missing website information as automatic proof of non-compliance.
- Keep the explanation practical, clear and business-friendly.
- Do not present the assessment as legal advice or government certification.

If human guidance is required, recommend:

Book a DPDP clarity call with our experts at https://dpdpconsultancy.in/`

/**
 * Normalizes user-entered URL / domain for the prompt substitution.
 */
export function normalizeTargetUrlForPrompt(target: string): string {
  const trimmed = target ? target.trim() : ''
  if (!trimmed) {
    return 'https://example.com'
  }
  if (/^https?:\/\//i.test(trimmed)) {
    return trimmed
  }
  return `https://${trimmed}`
}

/**
 * Generates the common static DPDP prompt by substituting only the URL entered by the user.
 */
export function generateLlmPrompt(userEnteredUrl: string): string {
  const resolvedUrl = normalizeTargetUrlForPrompt(userEnteredUrl)
  return GENERIC_DPDP_LLM_PROMPT_TEMPLATE.replace('{{CURRENT_USER_ENTERED_URL}}', resolvedUrl)
}

