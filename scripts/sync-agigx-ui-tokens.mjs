#!/usr/bin/env node

/**
 * sync-agigx-ui-tokens.mjs
 *
 * Reads the :root and [data-theme='light'] blocks from agigx-ui/src/app/globals.css
 * and regenerates dpdp-website/src/app/colors.css so the two apps cannot drift.
 *
 * Usage:  node scripts/sync-agigx-ui-tokens.mjs
 *
 * The script intentionally excludes sidebar-* tokens (not used by dpdp-website)
 * and keeps only the color / visual tokens needed for branding parity.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const AGIGX_UI_CSS = resolve(__dirname, '../../agigx-ui/src/app/globals.css')
const OUTPUT_CSS = resolve(__dirname, '../src/app/colors.css')

/** Tokens that belong to agigx-ui's console layout, not the marketing site. */
const SKIP_PREFIXES = ['--sidebar']

function extractBlock(css, selector) {
  // Match selector { ... } handling nested braces
  const escaped = selector.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  const re = new RegExp(`${escaped}\\s*\\{`, 'g')
  const match = re.exec(css)
  if (!match) return null

  let depth = 0
  let start = match.index + match[0].length
  let end = start

  for (let i = start; i < css.length; i++) {
    if (css[i] === '{') depth++
    if (css[i] === '}') {
      if (depth === 0) {
        end = i
        break
      }
      depth--
    }
  }

  return css.slice(start, end)
}

function parseVars(block) {
  const vars = []
  if (!block) return vars

  // Match CSS custom properties, including multi-line values
  const lines = block.split('\n')
  let currentVar = null
  let currentValue = ''

  for (const line of lines) {
    const trimmed = line.trim()
    if (!trimmed || trimmed.startsWith('/*') || trimmed.startsWith('*') || trimmed === '*/') {
      continue
    }

    const propMatch = trimmed.match(/^(--[\w-]+)\s*:\s*(.*)/)
    if (propMatch) {
      // Save previous var if any
      if (currentVar) {
        vars.push({ name: currentVar, value: currentValue.replace(/;\s*$/, '').trim() })
      }
      currentVar = propMatch[1]
      currentValue = propMatch[2]

      // Check if the value is complete (ends with ;)
      if (currentValue.endsWith(';')) {
        vars.push({ name: currentVar, value: currentValue.replace(/;\s*$/, '').trim() })
        currentVar = null
        currentValue = ''
      }
    } else if (currentVar) {
      // Continuation of multi-line value
      currentValue += '\n      ' + trimmed
      if (trimmed.endsWith(';')) {
        vars.push({ name: currentVar, value: currentValue.replace(/;\s*$/, '').trim() })
        currentVar = null
        currentValue = ''
      }
    }
  }

  // Save last var if it didn't end with ;
  if (currentVar) {
    vars.push({ name: currentVar, value: currentValue.replace(/;\s*$/, '').trim() })
  }

  return vars.filter(v => !SKIP_PREFIXES.some(p => v.name.startsWith(p)))
}

function formatBlock(selector, vars) {
  const indent = selector === ':root' ? '    ' : '    '
  const lines = vars.map(v => {
    // Multi-line values (like mesh-gradient) need special formatting
    if (v.value.includes('\n')) {
      return `${indent}${v.name}:\n${v.value.split('\n').map(l => `${indent}  ${l.trim()}`).join('\n')};`
    }
    return `${indent}${v.name}: ${v.value};`
  })
  return `  ${selector} {\n${lines.join('\n')}\n  }`
}

// --- Main ---
const source = readFileSync(AGIGX_UI_CSS, 'utf-8')

// We need to find vars in :root inside @layer base
const layerMatch = source.match(/@layer base\s*\{([\s\S]*?)(?=@layer)/)
const layerContent = layerMatch ? layerMatch[1] : source

const rootBlock = extractBlock(layerContent, ':root')
const lightBlock = extractBlock(layerContent, "[data-theme='light']")

const rootVars = parseVars(rootBlock)
const lightVars = parseVars(lightBlock)

if (rootVars.length === 0) {
  console.error('❌  No :root variables found in agigx-ui globals.css')
  process.exit(1)
}

const output = `/**
 * colors.css — AUTO-GENERATED by scripts/sync-agigx-ui-tokens.mjs
 *
 * Source: agigx-ui/src/app/globals.css
 * Do NOT edit by hand. Run: node scripts/sync-agigx-ui-tokens.mjs
 */

${formatBlock(':root', rootVars)}

${formatBlock("[data-theme='light']", lightVars)}
`

writeFileSync(OUTPUT_CSS, output, 'utf-8')
console.log(`✅  Wrote ${rootVars.length} root + ${lightVars.length} light vars → ${OUTPUT_CSS}`)
